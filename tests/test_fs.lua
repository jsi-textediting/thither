  H.eq(#p1.entries, 10); H.eq(p1.more, true)
  local p3 = c:request("readdir", { path = dir, offset = 20, limit = 10 })
  H.eq(#p3.entries, 8); H.eq(p3.more, false); H.eq(p3.entries[1].name, "file20")
  local _, err = c:request("readdir", { path = dir .. "/file01" })
  H.eq(err.code, "ENOTDIR")
  _, err = c:request("readdir", { path = dir .. "/missing" })
  H.eq(err.code, "ENOENT")
  c:close()
end)

