-- Filesystem op tests: stat, readdir, read, write (atomic, etag conflict,
-- streamed), mkdir, remove, rename, realpath.
local H = require "harness"
local U = require "util"
local Client = require "client"
local mp = require "thither.msgpack"

local function connect(args)
  return Client.connect({ args = args })
end

H.test("fs: stat of file, dir, symlink and missing path", function()
  local dir = U.tmpdir("stat")
  U.write_file(dir .. "/f.txt", "hello\n")
  U.sh("mkdir " .. dir .. "/d && ln -s f.txt " .. dir .. "/l && ln -s nowhere " .. dir .. "/dangling && chmod 640 " .. dir .. "/f.txt")
  local c = connect()
  local f = c:request("stat", { path = dir .. "/f.txt" })
  H.eq(f.type, "file"); H.eq(f.size, 6); H.eq(f.mode, tonumber("640", 8))
  H.ok(f.etag:match("^%d+%-6%-%d+$"), "etag format mtime_ns-size-inode: " .. f.etag)
  H.eq(f.etag, f.mtime_ns .. "-6-" .. f.ino)
  H.ok(math.abs(f.mtime - os.time()) < 60)
  H.eq(c:request("stat", { path = dir .. "/d" }).type, "dir")
  local l = c:request("stat", { path = dir .. "/l" })
  H.eq(l.type, "file"); H.eq(l.is_link, true); H.eq(l.link, "f.txt"); H.eq(l.size, 6)
  l = c:request("stat", { path = dir .. "/l", nofollow = true })
  H.eq(l.type, "symlink")
  H.eq(c:request("stat", { path = dir .. "/dangling" }).type, "symlink")
  local _, err = c:request("stat", { path = dir .. "/missing" })
  H.eq(err.code, "ENOENT")
  _, err = c:request("stat", { path = dir .. "/f.txt/x" })
  H.eq(err.code, "ENOTDIR")
  c:close()
end)

