H.test("fs: mkdir, parents, remove, recursive remove", function()
  local dir = U.tmpdir("mk")
  local c = connect()
  H.ok(c:request("mkdir", { path = dir .. "/a" }))
  local _, err = c:request("mkdir", { path = dir .. "/a" })
  H.eq(err.code, "EEXIST")
  _, err = c:request("mkdir", { path = dir .. "/x/y/z" })
  H.eq(err.code, "ENOENT")
  H.ok(c:request("mkdir", { path = dir .. "/x/y/z", parents = true }))
  H.ok(c:request("mkdir", { path = dir .. "/x/y/z", parents = true }), "parents is idempotent")
  H.eq(c:request("stat", { path = dir .. "/x/y/z" }).type, "dir")
  U.write_file(dir .. "/x/y/z/f", "1")
  U.write_file(dir .. "/x/y/g", "2")
  U.sh("ln -s " .. dir .. "/a " .. dir .. "/x/linktoa")
  _, err = c:request("remove", { path = dir .. "/x" })
  H.eq(err.code, "ENOTEMPTY")
  H.ok(c:request("remove", { path = dir .. "/x", recursive = true }))
  H.ok(not U.exists(dir .. "/x/y/g"))
  H.eq(c:request("stat", { path = dir .. "/a" }).type, "dir", "recursive remove must not follow symlinks")
  H.ok(c:request("remove", { path = dir .. "/a" }), "empty dir")
  U.write_file(dir .. "/file", "1")
  H.ok(c:request("remove", { path = dir .. "/file" }))
  _, err = c:request("remove", { path = dir .. "/file" })
  H.eq(err.code, "ENOENT")
  _, err = c:request("remove", { path = "/", recursive = true })
  H.eq(err.code, "EINVAL")
  c:close()
end)

