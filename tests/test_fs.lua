H.test("fs: copy is atomic, keeps modes and times on request", function()
  local dir = U.tmpdir("copy")
  local data = {}
  for i = 1, 200000 do data[i] = string.format("line %06d\n", i) end
  data = table.concat(data)   -- 2.2 MB
  U.write_file(dir .. "/a", data)
  U.sh("chmod 640 " .. dir .. "/a && touch -d @1000000000 " .. dir .. "/a")
  local c = connect()
  local st = c:request("copy", { from = dir .. "/a", to = dir .. "/b" })
  H.eq(st.size, #data)
  H.eq(U.sh("cmp " .. dir .. "/a " .. dir .. "/b && echo same"), "same\n")
  H.eq(U.sh("stat -c %a " .. dir .. "/b"), "640\n", "a new copy gets the source permissions")
  H.ok(st.mtime > 1000000000 + 1000, "mtime is now without keep_time")
  st = c:request("copy", { from = dir .. "/a", to = dir .. "/t", keep_time = true })
  H.eq(st.mtime_ns, 1000000000 * 1000000000)
  U.write_file(dir .. "/c", "old")
  U.sh("chmod 600 " .. dir .. "/c")
  local _, err = c:request("copy", { from = dir .. "/a", to = dir .. "/c", overwrite = false })
  H.eq(err.code, "EEXIST")
  H.eq(U.read_file(dir .. "/c"), "old")
  H.ok(c:request("copy", { from = dir .. "/a", to = dir .. "/c" }), "overwrite is the default")
  H.eq(U.sh("cmp " .. dir .. "/a " .. dir .. "/c && echo same"), "same\n")
  H.eq(U.sh("stat -c %a " .. dir .. "/c"), "600\n", "an overwritten file keeps its permissions")
  U.write_file(dir .. "/empty", "")
  H.eq(c:request("copy", { from = dir .. "/empty", to = dir .. "/empty2" }).size, 0)
  _, err = c:request("copy", { from = dir .. "/missing", to = dir .. "/x" })
  H.eq(err.code, "ENOENT")
  U.sh("mkdir " .. dir .. "/d")
  _, err = c:request("copy", { from = dir .. "/d", to = dir .. "/x" })
  H.eq(err.code, "EISDIR")
  _, err = c:request("copy", { from = dir .. "/a", to = dir .. "/d" })
  H.eq(err.code, "EISDIR")
  H.eq(U.ls(dir), { "a", "b", "c", "d", "empty", "empty2", "t" }, "no temp files left behind")
  c:close()
end)

