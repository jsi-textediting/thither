H.test("fs: read ranges, EOF and binary content", function()
  local dir = U.tmpdir("read")
  local all = {}
  for i = 0, 255 do all[#all + 1] = string.char(i) end
  local data = string.rep(table.concat(all), 100)
  U.write_file(dir .. "/bin", data)
  local c = connect()
  local r = c:request("read", { path = dir .. "/bin", offset = 0, len = #data })
  H.ok(r.data == data, "full read"); H.eq(r.eof, true)
  r = c:request("read", { path = dir .. "/bin", offset = 1000, len = 500 })
  H.ok(r.data == data:sub(1001, 1500)); H.eq(r.eof, false)
  r = c:request("read", { path = dir .. "/bin", offset = #data - 10, len = 500 })
  H.eq(#r.data, 10); H.eq(r.eof, true)
  r = c:request("read", { path = dir .. "/bin", offset = #data + 100, len = 10 })
  H.eq(r.data, ""); H.eq(r.eof, true)
  local _, err = c:request("read", { path = dir .. "/bin", offset = 0, len = 9 * 1024 * 1024 })
  H.eq(err.code, "too_large")
  _, err = c:request("read", { path = dir, offset = 0, len = 10 })
  H.eq(err.code, "EISDIR")
  _, err = c:request("read", { path = dir .. "/bin", offset = 0, len = 10, etag = "1-2-3" })
  H.eq(err.code, "stale")
  c:close()
end)

H.test("fs: write creates, replaces atomically and preserves mode", function()
  local dir = U.tmpdir("write")
  local c = connect()
  local st = c:request("write", { path = dir .. "/new.txt", data = "one", mode = tonumber("600", 8) })
  H.eq(st.size, 3); H.eq(st.mode, tonumber("600", 8))
  H.eq(U.read_file(dir .. "/new.txt"), "one")
  H.eq(U.ls(dir), { "new.txt" }, "no temp file left behind")
  -- replacing keeps the existing mode regardless of the mode argument
  U.sh("chmod 755 " .. dir .. "/new.txt")
  local st2 = c:request("write", { path = dir .. "/new.txt", data = "two!", mode = tonumber("600", 8) })
  H.eq(st2.mode, tonumber("755", 8))
  H.eq(U.read_file(dir .. "/new.txt"), "two!")
  H.ok(st2.etag ~= st.etag)
  -- setuid/setgid survive (chown of the temp file must come before chmod)
  U.sh("chmod 6755 " .. dir .. "/new.txt")
  local before = c:request("stat", { path = dir .. "/new.txt" }).mode
  local st3 = c:request("write", { path = dir .. "/new.txt", data = "three" })
  H.eq(st3.mode, before)
  -- binary data
  local bin = {}
  for i = 0, 255 do bin[#bin + 1] = string.char(i) end
  bin = table.concat(bin):rep(50)
  c:request("write", { path = dir .. "/bin", data = mp.bin(bin) })
  H.ok(U.read_file(dir .. "/bin") == bin)
  -- empty file
  c:request("write", { path = dir .. "/empty", data = "" })
  H.eq(U.read_file(dir .. "/empty"), "")
  -- writing to a directory or missing parent fails
  local _, err = c:request("write", { path = dir, data = "x" })
  H.eq(err.code, "EISDIR")
  _, err = c:request("write", { path = dir .. "/no/such/dir/f", data = "x" })
  H.eq(err.code, "ENOENT")
  H.ok(c:request("write", { path = dir .. "/no/such/dir/f", data = "x", create_dirs = true }))
  H.eq(U.read_file(dir .. "/no/such/dir/f"), "x")
  H.eq(U.ls(dir .. "/no/such/dir"), { "f" })
  c:close()
end)

H.test("fs: write is atomic (readers see old or new, never partial)", function()
  local dir = U.tmpdir("atomic")
  local old = string.rep("A", 4 * 1024 * 1024)
  local new = string.rep("B", 4 * 1024 * 1024)
  U.write_file(dir .. "/f", old)
  local c = connect()
  local begin = c:request("write_begin", { path = dir .. "/f" })
  -- stream the new content in 256 KiB chunks: the target must stay untouched
  local ino_before = U.sh("stat -c %i " .. dir .. "/f")
  for off = 1, #new, 256 * 1024 do
    c:request("write_chunk", { wid = begin.wid, data = mp.bin(new:sub(off, off + 256 * 1024 - 1)) })
    H.ok(U.read_file(dir .. "/f") == old, "target changed before commit")
  end
  local temps = U.ls(dir)
  H.eq(#temps, 2, "one temp file while the write is open")
  local st = c:request("write_commit", { wid = begin.wid })
  H.eq(st.size, #new)
  H.ok(U.read_file(dir .. "/f") == new)
  H.eq(U.ls(dir), { "f" })
  H.ok(U.sh("stat -c %i " .. dir .. "/f") ~= ino_before, "replaced via rename")
  -- abort leaves the file as is and removes the temp file
  local b2 = c:request("write_begin", { path = dir .. "/f" })
  c:request("write_chunk", { wid = b2.wid, data = "partial" })
  H.ok(c:request("write_abort", { wid = b2.wid }))
  H.ok(U.read_file(dir .. "/f") == new)
  H.eq(U.ls(dir), { "f" })
  local _, err = c:request("write_commit", { wid = b2.wid })
  H.eq(err.code, "no_stream")
  -- a dropped connection mid-write leaves nothing behind
  local c2 = connect()
  local b3 = c2:request("write_begin", { path = dir .. "/f" })
  c2:request("write_chunk", { wid = b3.wid, data = "dangling" })
  c2:close()
  H.eq(U.ls(dir), { "f" })
  H.ok(U.read_file(dir .. "/f") == new)
  c:close()
end)

H.test("fs: if_match detects conflicts", function()
  local dir = U.tmpdir("etag")
  local c = connect()
  local st = c:request("write", { path = dir .. "/f", data = "v1", if_match = "-" })
  local _, err = c:request("write", { path = dir .. "/f", data = "v1b", if_match = "-" })
  H.eq(err.code, "conflict", "file exists but if_match is '-'")
  H.eq(err.etag, st.etag)
  H.eq(U.read_file(dir .. "/f"), "v1")
  local st2 = c:request("write", { path = dir .. "/f", data = "v2", if_match = st.etag })
  H.eq(U.read_file(dir .. "/f"), "v2")
  -- stale etag
  _, err = c:request("write", { path = dir .. "/f", data = "v3", if_match = st.etag })
  H.eq(err.code, "conflict")
  H.eq(err.etag, st2.etag)
  H.eq(U.read_file(dir .. "/f"), "v2")
  H.eq(U.ls(dir), { "f" }, "temp file removed after a conflict")
  -- out-of-band modification is detected (same size, new mtime)
  U.sh("sleep 0.05; printf v9 > " .. dir .. "/f")
  _, err = c:request("write", { path = dir .. "/f", data = "v4", if_match = st2.etag })
  H.eq(err.code, "conflict")
  -- deleted file
  U.sh("rm " .. dir .. "/f")
  _, err = c:request("write", { path = dir .. "/f", data = "v5", if_match = st2.etag })
  H.eq(err.code, "conflict"); H.eq(err.etag, "-")
  -- streamed writes honour if_match at commit time
  local cur = c:request("write", { path = dir .. "/g", data = "g1" })
  local b = c:request("write_begin", { path = dir .. "/g", if_match = cur.etag })
  c:request("write_chunk", { wid = b.wid, data = "g2" })
  U.sh("sleep 0.05; printf zz > " .. dir .. "/g")
  _, err = c:request("write_commit", { wid = b.wid })
  H.eq(err.code, "conflict")
  H.eq(U.read_file(dir .. "/g"), "zz")
  c:close()
end)

